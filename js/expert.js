function selectLoveLang(i) {
  selectedLoveLang = i;
  showExpertSection("love");
}

function toggleCheck(key) {
  if(completedChecks.has(key)) completedChecks.delete(key);
  else completedChecks.add(key);
  showExpertSection("checklist");
}

function nextQuestion() {
  if(aronQuestionIndex < aronQuestions.length - 1) {
    aronQuestionIndex++;
    showExpertSection("questions");
    document.getElementById("expertContent").scrollIntoView({behavior:"smooth", block:"start"});
  }
}

function prevQuestion() {
  if(aronQuestionIndex > 0) {
    aronQuestionIndex--;
    showExpertSection("questions");
  }
}

function randomQuestion() {
  const prev = aronQuestionIndex;
  do { aronQuestionIndex = Math.floor(Math.random() * aronQuestions.length); }
  while(aronQuestionIndex === prev && aronQuestions.length > 1);
  showExpertSection("questions");
}

function jumpToCategory(startIdx) {
  aronQuestionIndex = Math.min(startIdx, aronQuestions.length - 1);
  showExpertSection("questions");
}
