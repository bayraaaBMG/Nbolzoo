let currentGiftCat = "personal";

function showGiftTab(tab) {
  if(tab === "gifts") {
    document.getElementById("giftsContent").style.display = "block";
    document.getElementById("proposalsContent").style.display = "none";
    document.getElementById("giftTabBtn").className = "btn btn-primary";
    document.getElementById("proposalTabBtn").className = "btn btn-ghost";
    renderGifts();
  } else {
    document.getElementById("giftsContent").style.display = "none";
    document.getElementById("proposalsContent").style.display = "block";
    document.getElementById("giftTabBtn").className = "btn btn-ghost";
    document.getElementById("proposalTabBtn").className = "btn btn-primary";
    renderProposals();
  }
}

function renderGifts() {
  const tabs = document.getElementById("giftCatTabs");
  tabs.innerHTML = giftCategories.map(c => {
    const count = gifts.filter(g => g.cat === c.id).length;
    return `<div class="gift-cat-tab ${currentGiftCat===c.id?'active':''}" onclick="setGiftCat('${c.id}')">
      ${c.emoji} ${c.name} <span class="tab-count">${count}</span>
    </div>`;
  }).join("");

  const filtered = gifts.filter(g => g.cat === currentGiftCat);
  document.getElementById("giftGrid").innerHTML = filtered.map((g, idx) => {
    const gIdx = gifts.indexOf(g);
    return `
    <div class="gift-card" onclick="openGiftModal(${gIdx})">
      <span class="gift-emoji">${g.emoji}</span>
      <h4>${g.title}</h4>
      <div class="gift-desc">${g.desc}</div>
      <div class="gift-price">💰 ${g.price}</div>
      <div class="gift-why">💡 ${g.why}</div>
    </div>`;
  }).join("");
}

function openGiftModal(idx) {
  const g = gifts[idx];
  if(!g) return;
  const cat = giftCategories.find(c => c.id === g.cat) || {};
  document.getElementById("modalContent").innerHTML = `
    <div class="modal-header">
      <h3>${g.emoji} ${g.title}</h3>
      <button class="modal-close" onclick="closeModal()" type="button">✕</button>
    </div>
    <div class="modal-body">
      <div style="height:120px; background:linear-gradient(135deg,var(--primary-soft),var(--accent-soft)); border-radius:12px; display:flex; align-items:center; justify-content:center; font-size:56px; margin-bottom:16px;">${g.emoji}</div>
      <div class="modal-meta">
        <span class="modal-meta-item">${cat.emoji||''} ${cat.name||''}</span>
        <span class="modal-meta-item">💰 ${g.price}</span>
      </div>
      <p style="font-size:14px; line-height:1.7; color:var(--text); margin-bottom:14px;">${g.desc}</p>
      <div class="feeling-box">
        <h4>💡 Яагаад энэ бэлэг хамаарах вэ?</h4>
        <p>${g.why}</p>
      </div>
      <button class="btn btn-accent" style="width:100%; margin-top:14px;" onclick="showToast('💝 ${g.title.replace(/'/g,'')} хадгалагдлаа!'); closeModal();" type="button">💝 Бэлгийн жагсаалтад нэмэх</button>
    </div>`;
  document.getElementById("modal").classList.add("show");
}

function setGiftCat(catId) {
  currentGiftCat = catId;
  renderGifts();
}

